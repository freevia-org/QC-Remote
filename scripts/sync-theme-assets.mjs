// Synchronizes the Android app's generated resources from the single source
// of truth in @qc-remote/theme (packages/typescript/qc-theme). Scoped to the
// Android target only -- this repo's Windows app is built and branded
// separately and is out of scope for this script.
//
// Usage:
//   node scripts/sync-theme-assets.mjs          # regenerate the files
//   node scripts/sync-theme-assets.mjs --check  # verify they are current, exit 1 if stale

import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const check = process.argv.includes("--check");
const nativeTheme = JSON.parse(
  await readFile(resolve(root, "packages/typescript/qc-theme/src/native-theme.json"), "utf8")
);
const brand = JSON.parse(
  await readFile(resolve(root, "packages/typescript/qc-theme/src/brand.json"), "utf8")
);
const upper = (value) => value.toUpperCase();

const generatedText = [
  [
    "apps/android/android/app/src/main/res/values/colors.xml",
    `<?xml version="1.0" encoding="utf-8"?>
<resources>
    <!-- Generated by scripts/sync-theme-assets.mjs from @qc-remote/theme. -->
    <color name="colorPrimary">${upper(nativeTheme.android.primary)}</color>
    <color name="colorPrimaryDark">${upper(nativeTheme.android.background)}</color>
    <color name="colorAccent">${upper(nativeTheme.android.accent)}</color>
    <color name="brandBackground">${upper(nativeTheme.android.background)}</color>
    <color name="brandScreen">${upper(nativeTheme.android.brandScreen)}</color>
</resources>
`,
  ],
  [
    "apps/android/android/app/src/main/res/values/ic_launcher_background.xml",
    `<?xml version="1.0" encoding="utf-8"?>
<resources>
    <!-- Generated by scripts/sync-theme-assets.mjs from @qc-remote/theme. -->
    <color name="ic_launcher_background">${upper(nativeTheme.android.launcherBackground)}</color>
</resources>
`,
  ],
  [
    "apps/android/android/app/src/main/res/values/strings.xml",
    `<?xml version="1.0" encoding="utf-8"?>
<resources>
    <!-- Generated by scripts/sync-theme-assets.mjs from @qc-remote/theme. -->
    <string name="app_name">${brand.appName}</string>
    <string name="title_activity_main">${brand.appName}</string>
    <string name="device_name">${brand.deviceName}</string>
    <string name="download_folder">${brand.appName}</string>
    <string name="relay_notification_title">${brand.appName} relay</string>
    <string name="app_font_family">${nativeTheme.android.appFontFamily}</string>
    <string name="package_name">${brand.androidPackage}</string>
    <string name="custom_url_scheme">${brand.androidPackage}</string>
</resources>
`,
  ],
];

const brandedJson = [
  [
    "apps/android/capacitor.config.json",
    () => ({
      appId: brand.androidPackage,
      appName: brand.appName,
      webDir: "dist",
      backgroundColor: nativeTheme.android.background,
      loggingBehavior: "none",
      android: {
        allowMixedContent: false,
        backgroundColor: nativeTheme.android.background,
      },
      plugins: {
        StatusBar: {
          style: "DARK",
          backgroundColor: nativeTheme.android.background,
        },
      },
    }),
  ],
];

// Every target is pinned to LF by .gitattributes, and writes are byte-exact:
// an already-correct file is left untouched, and a CRLF copy is repaired. This
// used to terminate capacitor.config.json with `\r\n`, which Git then reported
// as modified for ever while `git diff` stayed empty - the normalised bytes
// match the blob, but the working size never matches the index again - so
// every android:sync dirtied the checkout it ran in.
const writeIfChanged = async (targetPath, content) => {
  const current = await readFile(targetPath, "utf8").catch(() => "");
  if (current !== content) await writeFile(targetPath, content);
};

let stale = false;
for (const [target, content] of generatedText) {
  const targetPath = resolve(root, target);
  if (check) {
    const current = await readFile(targetPath, "utf8").catch(() => "");
    if (current.replaceAll("\r\n", "\n") !== content) {
      console.error(`${target} is not generated from @qc-remote/theme`);
      stale = true;
    }
  } else {
    await writeIfChanged(targetPath, content);
  }
}
for (const [target, transform] of brandedJson) {
  const targetPath = resolve(root, target);
  const current = JSON.parse(await readFile(targetPath, "utf8"));
  const expected = transform(current);
  if (check) {
    if (JSON.stringify(current) !== JSON.stringify(expected)) {
      console.error(`${target} branding is not synchronized with @qc-remote/theme`);
      stale = true;
    }
  } else {
    await writeIfChanged(targetPath, `${JSON.stringify(expected, null, 2)}\n`);
  }
}
if (stale) process.exitCode = 1;
