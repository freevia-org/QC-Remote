"""Authoring contract tests; no native renderer, device or app dependencies."""
import contextlib
import builtins
import importlib.util
import io
import tempfile
import unittest
from pathlib import Path
from types import SimpleNamespace as S
from unittest.mock import patch

SPEC = importlib.util.spec_from_file_location("header_font", Path(__file__).with_name("generate-coros-header-font.py"))
catalog = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(catalog)
REPO = Path(__file__).resolve().parents[1]


def value(**kwargs):
    return S(**kwargs)


def pair(amount=-54, second=None):
    return S(SecondGlyph="V", Value1=value(XAdvance=amount), Value2=second)


def format_one(amount=-54, second=None):
    return S(Format=1, Coverage=S(glyphs=["A"]), PairSet=[S(PairValueRecord=[pair(amount, second)])])


class CatalogTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.raw = (REPO / catalog.FONT_PATH).read_bytes()
        cls.license = (REPO / catalog.LICENSE_PATH).read_bytes()
        cls.expected = catalog.generate_catalog(cls.raw, cls.license)

    def test_qualified_font_generates_identical_lf_bytes_and_checks(self):
        self.assertEqual(self.expected, catalog.generate_catalog(self.raw, self.license))
        self.assertNotIn(b"\r", self.expected)
        with tempfile.TemporaryDirectory(prefix="header-font-test-") as temporary:
            output = Path(temporary) / "catalog.ts"
            catalog.run(REPO, output, write=True)
            before = output.stat().st_mtime_ns
            catalog.run(REPO, output)
            self.assertEqual(before, output.stat().st_mtime_ns, "Check must not rewrite identical output")
            self.assertEqual(self.expected, output.read_bytes())

    def test_check_refuses_each_data_class_without_rewriting(self):
        mutations = [(b"advanceUnits:236", b"advanceUnits:237"),
                     (b'path:"M', b'path:"M1 '),
                     (b"bounds:[103", b"bounds:[104"),
                     (b'"65,86":-54', b'"65,86":-53'),
                     (b'"fallbackLigatureSequences":["fi"]', b'"fallbackLigatureSequences":[]'),
                     (catalog.QUALIFIED_FONT_SHA256.encode(), b"0" * 64)]
        with tempfile.TemporaryDirectory(prefix="header-font-test-") as temporary:
            output = Path(temporary) / "catalog.ts"
            for before, after in mutations:
                with self.subTest(field=before):
                    self.assertIn(before, self.expected, "Mutation must actually edit generated bytes")
                    changed = self.expected.replace(before, after, 1)
                    output.write_bytes(changed)
                    with self.assertRaisesRegex(catalog.CatalogError, "differs"):
                        catalog.run(REPO, output)
                    self.assertEqual(output.read_bytes(), changed)

    def test_invalid_font_and_license_refuse_before_output_write(self):
        with tempfile.TemporaryDirectory(prefix="header-font-test-") as temporary:
            repo = Path(temporary)
            font = repo / catalog.FONT_PATH
            license = repo / catalog.LICENSE_PATH
            font.parent.mkdir(parents=True)
            license.write_bytes(self.license)
            output = repo / "existing.ts"
            output.write_bytes(b"keep")
            for malformed in [b"", b"invalid TrueType", self.raw[:-1] + bytes([self.raw[-1] ^ 1])]:
                font.write_bytes(malformed)
                with self.assertRaises(catalog.CatalogError):
                    catalog.run(repo, output, write=True)
                self.assertEqual(output.read_bytes(), b"keep")
            font.write_bytes(self.raw)
            license.write_bytes(b"unrelated license")
            with self.assertRaisesRegex(catalog.CatalogError, "copyright/OFL"):
                catalog.run(repo, output, write=True)
            self.assertEqual(output.read_bytes(), b"keep")

    def test_correct_copyright_line_does_not_admit_truncated_or_replaced_license(self):
        with tempfile.TemporaryDirectory(prefix="header-font-test-") as temporary:
            repo = Path(temporary)
            font = repo / catalog.FONT_PATH
            license = repo / catalog.LICENSE_PATH
            font.parent.mkdir(parents=True)
            font.write_bytes(self.raw)
            output = repo / "existing.ts"
            output.write_bytes(b"preserve existing output")
            first_line = self.license.splitlines(keepends=True)[0]
            for changed in [first_line, first_line + b"\nReplaced license body\n",
                            self.license.replace(b"PERMISSION", b"PROHIBITION", 1)]:
                with self.subTest(license_bytes=len(changed)):
                    self.assertNotEqual(changed, self.license)
                    self.assertTrue(changed.startswith(first_line))
                    license.write_bytes(changed)
                    with self.assertRaisesRegex(catalog.CatalogError, "copyright/OFL"):
                        catalog.run(repo, output, write=True)
                    self.assertEqual(output.read_bytes(), b"preserve existing output")

    def test_missing_inputs_output_and_wrong_tool_version_are_not_passes(self):
        with tempfile.TemporaryDirectory(prefix="header-font-test-") as temporary:
            with self.assertRaisesRegex(catalog.CatalogError, "missing/unreadable"):
                catalog.run(Path(temporary), Path(temporary) / "catalog.ts")
            with self.assertRaisesRegex(catalog.CatalogError, "Catalog is missing"):
                catalog.run(REPO, Path(temporary) / "missing.ts")
        import fontTools
        with patch.object(fontTools, "__version__", "unqualified"):
            with self.assertRaisesRegex(catalog.CatalogError, "4.65.0 required"):
                catalog.generate_catalog(self.raw, self.license)

    def test_missing_authoring_dependency_has_actionable_failure(self):
        original_import = builtins.__import__
        def missing(name, *args, **kwargs):
            if name == "fontTools":
                raise ImportError("fixture missing fontTools")
            return original_import(name, *args, **kwargs)
        with patch("builtins.__import__", side_effect=missing):
            with self.assertRaisesRegex(catalog.CatalogError, "install scripts/requirements-font-authoring.txt"):
                catalog.authoring_tools()

    def test_cli_check_failure_is_explicit(self):
        with tempfile.TemporaryDirectory(prefix="header-font-test-") as temporary:
            stream = io.StringIO()
            with contextlib.redirect_stderr(stream):
                self.assertEqual(catalog.main(["--check", "--output", str(Path(temporary) / "absent")]), 1)
            self.assertIn("Header catalog refused", stream.getvalue())

    def test_gpos_format1_coverage_and_zero_adjustment(self):
        table = format_one(0)
        self.assertEqual(catalog.pair_in_subtable(table, "A", "V"), 0)
        self.assertIsNone(catalog.pair_in_subtable(table, "B", "V"))
        self.assertIsNone(catalog.pair_in_subtable(table, "A", "W"))
        self.assertEqual(catalog.pair_in_subtable(format_one(), "A", "V"), -54)

    def test_gpos_format2_includes_class_zero_but_not_uncovered_left(self):
        table = S(Format=2, Coverage=S(glyphs=["A", "T"]),
                  ClassDef1=S(classDefs={"T": 1}), ClassDef2=S(classDefs={"V": 1}),
                  Class1Record=[S(Class2Record=[pair(0), pair(-54)]), S(Class2Record=[pair(8), pair(-12)])])
        self.assertEqual(catalog.pair_in_subtable(table, "A", "V"), -54)
        self.assertEqual(catalog.pair_in_subtable(table, "T", "W"), 8)
        self.assertEqual(catalog.pair_in_subtable(table, "A", "W"), 0)
        self.assertIsNone(catalog.pair_in_subtable(table, "B", "V"))

    def test_extension_and_unsupported_positioning_fail_closed(self):
        table = format_one()
        extension = S(Format=1, ExtensionLookupType=2, ExtSubTable=table)
        self.assertEqual(catalog.pair_subtables(S(LookupFlag=0, LookupType=9, SubTable=[extension])), [table])
        with self.assertRaises(catalog.CatalogError):
            catalog.pair_subtables(S(LookupFlag=8, LookupType=2, SubTable=[table]))
        with self.assertRaises(catalog.CatalogError):
            catalog.pair_subtables(S(LookupFlag=0, LookupType=1, SubTable=[table]))
        for second in [value(XAdvance=1), value(XPlacement=1)]:
            with self.assertRaises(catalog.CatalogError):
                catalog.pair_in_subtable(format_one(second=second), "A", "V")
        with self.assertRaises(catalog.CatalogError):
            catalog.advance_only(value(XAdvance=3, YPlacement=2))

    def test_default_ligatures_are_explicit_whole_run_fallback(self):
        table = S(ligatures={"f": [S(Component=["i"], LigGlyph="fi")]})
        feature = S(FeatureTag="liga", Feature=S(LookupListIndex=[0]))
        gsub = S(FeatureList=S(FeatureRecord=[feature]), LookupList=S(Lookup=[S(LookupFlag=0, LookupType=4, SubTable=[table])]))
        self.assertEqual(catalog.ligatures_for_ascii(gsub, {"f": "f", "i": "i"}), ["fi"])
        gsub.LookupList.Lookup[0].LookupType = 6
        with self.assertRaises(catalog.CatalogError):
            catalog.ligatures_for_ascii(gsub, {"f": "f", "i": "i"})

    def test_all_ascii_composition_is_refused_but_non_ascii_context_is_safe(self):
        feature = S(FeatureTag="ccmp", Feature=S(LookupListIndex=[0]))
        table = S(Format=3, BacktrackCoverage=[], InputCoverage=[S(glyphs=["i"])], LookAheadCoverage=[S(glyphs=["acute"])])
        lookup = S(LookupFlag=0, LookupType=6, SubTable=[table])
        gsub = S(FeatureList=S(FeatureRecord=[feature]), LookupList=S(Lookup=[lookup]))
        catalog.require_non_ascii_composition(gsub, {"i", "f"})
        table.LookAheadCoverage[0].glyphs = ["f"]
        with self.assertRaisesRegex(catalog.CatalogError, "ASCII contextual"):
            catalog.require_non_ascii_composition(gsub, {"i", "f"})


if __name__ == "__main__":
    unittest.main()
