import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const schema = JSON.parse(fs.readFileSync(path.join(root, "contracts/public/qc-backup-report.v1.json"), "utf8"));
const p = schema.properties;
const statuses = p.status.enum;
const reasons = p.reason.enum;
const pascal = value => value.split("_").map(part => part[0].toUpperCase() + part.slice(1)).join("");
const snake = value => value.replace(/[A-Z]/g, match => `_${match.toLowerCase()}`);
const constants = Object.entries(schema["x-inspection-limits"]);
const branches = schema.allOf.map(branch => ({ status: branch.if.properties.status.const, ...branch.then.properties }));
const branchFor = reason => branches.find(branch => branch.reason.const === reason || branch.reason.enum?.includes(reason));
for (const reason of reasons) if (!branchFor(reason)) throw new Error(`Missing report status for ${reason}`);

let ts = "// Generated by scripts/generate-backup-checksum.mjs; do not edit.\n";
ts += "export interface BackupChecksumReportV1 {\n";
for (const [name, field] of Object.entries(p)) {
  const type = "const" in field ? JSON.stringify(field.const) : field.enum.map(item => JSON.stringify(item)).join(" | ");
  ts += `  ${name}: ${type};\n`;
}
ts += "}\n";
ts += `export const BACKUP_CHECKSUM_MESSAGES = ${JSON.stringify(Object.fromEntries(branches.map(b => [b.status, b.message.const])), null, 2)} as const;\n`;
const templateFor = reason => {
  const branch = branchFor(reason);
  return Object.fromEntries(Object.entries(p).map(([name, field]) => [name,
    "const" in field ? field.const : name === "status" ? branch.status : name === "reason" ? reason
      : name === "checkedLayout" ? branch.checkedLayout.const : branch.message.const]));
};
ts += `\nconst REPORTS = ${JSON.stringify(Object.fromEntries(reasons.map(reason => [reason, templateFor(reason)])), null, 2)} as const;\n`;
ts += `\n/** Validate the exact content-free report before any host metadata implies a checksum match. */
export function isBackupChecksumReportV1(value: unknown): value is BackupChecksumReportV1 {
  try {
    if (value === null || typeof value !== "object" || Array.isArray(value)) return false;
    const record = value as Record<string, unknown>;
    if (typeof record.reason !== "string" || !Object.hasOwn(REPORTS, record.reason)) return false;
    const expected = REPORTS[record.reason as keyof typeof REPORTS];
    const fields = Object.keys(expected) as (keyof BackupChecksumReportV1)[];
    return Object.keys(record).length === fields.length
      && fields.every(key => Object.hasOwn(record, key) && record[key] === expected[key]);
  } catch { return false; }
}
`;

let rust = "// Generated by scripts/generate-backup-checksum.mjs; do not edit.\nuse serde::Serialize;\n\n";
for (const [name, value] of constants) rust += `${name === "maximumJsonBytes" ? "/// Maximum JSON bytes admitted for optional checksum inspection.\n" : ""}${name === "maximumJsonBytes" ? "pub" : "pub(super)"} const ${snake(name).toUpperCase()}: usize = ${value.toLocaleString("en-US").replaceAll(",", "_")};\n`;
for (const [name, values] of [["BackupChecksumStatus", statuses], ["BackupChecksumReason", reasons]]) {
  rust += `\n/// Content-free advisory backup checksum ${name.endsWith("Status") ? "status" : "reason"}.\n#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize)]\n#[serde(rename_all = "snake_case")]\npub enum ${name} {\n`;
  for (const value of values) rust += `    /// The declared ${value.replaceAll("_", " ")} outcome.\n    ${pascal(value)},\n`;
  rust += "}\n";
}
rust += "\n/// Advisory metadata kept beside the saved file result, never inside its document.\n#[derive(Debug, Clone, PartialEq, Eq, Serialize)]\n#[serde(rename_all = \"camelCase\")]\npub struct BackupChecksumReportV1 {\n";
for (const [name, field] of Object.entries(p)) {
  const type = name === "status" ? "BackupChecksumStatus" : name === "reason" ? "BackupChecksumReason" : name === "checkedLayout" ? "Option<&'static str>" : typeof field.const === "boolean" ? "bool" : typeof field.const === "number" ? "u8" : "&'static str";
  rust += `    /// The contract's ${name} field.\n    pub ${snake(name)}: ${type},\n`;
}
rust += "}\n\n#[rustfmt::skip]\nimpl BackupChecksumReportV1 {\n    /// Build the fixed, content-free report for one declared reason.\n    pub fn from_reason(reason: BackupChecksumReason) -> Self {\n        let status = match reason {\n";
for (const reason of reasons) rust += `            BackupChecksumReason::${pascal(reason)} => BackupChecksumStatus::${pascal(branchFor(reason).status)},\n`;
rust += "        };\n        let (checked_layout, message) = match status {\n";
for (const b of branches) rust += `            BackupChecksumStatus::${pascal(b.status)} => (${b.checkedLayout.const === null ? "None" : `Some(${JSON.stringify(b.checkedLayout.const)})`}, ${JSON.stringify(b.message.const)}),\n`;
rust += `        };\n        Self {\n            schema_version: ${p.schemaVersion.const},\n            algorithm: ${JSON.stringify(p.algorithm.const)},\n            status,\n            checked_layout,\n            reason,\n            message,\n`;
for (const [name, field] of Object.entries(p)) if (typeof field.const === "boolean") rust += `            ${snake(name)}: ${field.const},\n`;
rust += "        }\n    }\n}\n";

const fallback = Object.fromEntries(Object.entries(p).map(([name, field]) => [name, "const" in field ? field.const : name === "status" ? "unknown_layout" : name === "reason" ? "internal_unavailable" : name === "message" ? branches.find(b => b.status === "unknown_layout").message.const : null]));
const reasonJson = reason => {
  const branch = branchFor(reason);
  return JSON.stringify({ ...fallback, status: branch.status, reason, checkedLayout: branch.checkedLayout.const, message: branch.message.const });
};
const java = `// Generated by scripts/generate-backup-checksum.mjs; do not edit.\npackage org.freevia.qcremote;\n\nfinal class GeneratedBackupChecksum {\n    static final int MAXIMUM_JSON_BYTES = ${schema["x-inspection-limits"].maximumJsonBytes};\n    static final String UNAVAILABLE_JSON = ${JSON.stringify(JSON.stringify(fallback))};\n    static String jsonForReason(String reason) {\n        switch (reason) {\n${reasons.map(reason => `            case ${JSON.stringify(reason)}: return ${JSON.stringify(reasonJson(reason))};`).join("\n")}\n            default: return UNAVAILABLE_JSON;\n        }\n    }\n    private GeneratedBackupChecksum() {}\n}\n`;
const outputs = new Map([
  ["packages/typescript/qc-client/src/generated-backup-checksum.ts", ts],
  ["packages/rust/quadcortex/src/backup/generated_integrity.rs", rust],
  ["apps/android/android/app/src/main/java/org/freevia/qcremote/GeneratedBackupChecksum.java", java],
]);
let drift = false;
for (const [relative, content] of outputs) {
  const target = path.join(root, relative);
  const old = fs.existsSync(target) ? fs.readFileSync(target, "utf8").replaceAll("\r\n", "\n") : "";
  if (old === content) continue;
  if (process.argv.includes("--check")) { console.error(`Backup checksum contract drift: ${relative}`); drift = true; }
  else { fs.mkdirSync(path.dirname(target), { recursive: true }); fs.writeFileSync(target, content); }
}
if (drift) process.exitCode = 1;
